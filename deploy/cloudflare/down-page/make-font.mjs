// Writes font.ts: Lexend Deca 400 (latin), the app's font, as base64 for the down page to embed (the
// server it would load from is the one that's down). Run after a @fontsource/lexend-deca update:
//   node deploy/cloudflare/down-page/make-font.mjs
// worker.test.ts fails while font.ts differs from the package's file.
import { readFileSync, writeFileSync } from 'node:fs';

const font = new URL('../../../web/node_modules/@fontsource/lexend-deca/files/lexend-deca-latin-400-normal.woff2', import.meta.url);
const out = new URL('./font.ts', import.meta.url);
const b64 = readFileSync(font).toString('base64');
writeFileSync(
  out,
  `// Generated by make-font.mjs from web/node_modules/@fontsource/lexend-deca/files/lexend-deca-latin-400-normal.woff2
// (SIL Open Font License 1.1). Don't edit.
export const LEXEND_DECA_400 = '${b64}';
`,
);
console.log(`font.ts: ${b64.length} base64 characters`);
